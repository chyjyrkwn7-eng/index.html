def load_icon_module():
    """gen-app-icon.py draws the icon; this borrows it rather than redrawing."""
    path = os.path.join(ROOT, "tools", "gen-app-icon.py")
    spec = importlib.util.spec_from_file_location("gen_app_icon", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def hex_rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def vertical_gradient(w, h, top, bottom):
    t, b = hex_rgb(top), hex_rgb(bottom)
    img = Image.new("RGB", (w, h))
    px = img.load()
    for y in range(h):
        f = y / max(1, h - 1)
        col = tuple(round(t[i] + (b[i] - t[i]) * f) for i in range(3))
        for x in range(w):
            px[x, y] = col
    return img


def radial_glow(w, h, cx, cy, radius, colour, strength):
    """One of the app's ambient glows, so the card reads as the same surface."""
    layer = Image.new("L", (w, h), 0)
    d = ImageDraw.Draw(layer)
    d.ellipse([cx - radius, cy - radius * 0.72, cx + radius, cy + radius * 0.72],
              fill=int(255 * strength))
    layer = layer.filter(ImageFilter.GaussianBlur(radius * 0.45))
    return Image.composite(Image.new("RGB", (w, h), hex_rgb(colour)),
                           Image.new("RGB", (w, h), (0, 0, 0)), layer), layer


def load_font(size, bold=True):
    from PIL import ImageFont
    candidates = [
        "/usr/share/fonts/truetype/dejavu/DejaVuSerif-Bold.ttf" if bold
        else "/usr/share/fonts/truetype/dejavu/DejaVuSerif.ttf",
        "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf" if bold
        else "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
    ]
    for c in candidates:
        if os.path.exists(c):
            return ImageFont.truetype(c, size)
    return ImageFont.load_default()


def gradient_text(text, font, stops):
    """The wordmark's gold-to-magenta ramp, clipped to the glyphs.

    Mapped across the TEXT's own bounding box, not across some larger
    canvas - the same mistake the app icon's V made, where a ramp spread
    over the whole tile left the gold and the magenta off the ends of the
    shape and the glyph came out uniformly salmon.
    """
    from PIL import ImageFont
    probe = Image.new("L", (8, 8))
    box = ImageDraw.Draw(probe).textbbox((0, 0), text, font=font)
    w, h = box[2] - box[0] + 4, box[3] - box[1] + 4
    off = (-box[0] + 2, -box[1] + 2)
    mask = Image.new("L", (w, h), 0)
    ImageDraw.Draw(mask).text(off, text, font=font, fill=255)
    ramp = Image.new("RGB", (w, h))
    px = ramp.load()
    cols = [hex_rgb(c) for c in stops]
    for x in range(w):
        f = x / max(1, w - 1) * (len(cols) - 1)
        i = min(int(f), len(cols) - 2)
        t = f - i
        col = tuple(round(cols[i][k] + (cols[i + 1][k] - cols[i][k]) * t) for k in range(3))
        for y in range(h):
            px[x, y] = col
    out = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    out.paste(ramp, (0, 0), mask)
    return out


def build_card(icon):
    card = vertical_gradient(CARD_W, CARD_H, BG_TOP, BG_BOTTOM)
    for cx, cy, r, col, strength in [
        (CARD_W * 0.18, CARD_H * 0.22, CARD_W * 0.42, BRAND[0], 0.16),
        (CARD_W * 0.86, CARD_H * 0.84, CARD_W * 0.40, BRAND[2], 0.14),
    ]:
        glow, mask = radial_glow(CARD_W, CARD_H, cx, cy, r, col, strength)
        card = Image.blend(card, Image.blend(card, glow, 0.55), 1.0) \
            if False else Image.composite(Image.blend(card, glow, 0.5), card, mask)

    tile = icon.resize((300, 300), Image.LANCZOS).convert("RGBA")
    # iOS's own corner radius, near enough, so the tile reads as an app icon
    # rather than as a photograph of a square.
    mask = Image.new("L", (300 * 4, 300 * 4), 0)
    ImageDraw.Draw(mask).rounded_rectangle([0, 0, 300 * 4 - 1, 300 * 4 - 1],
                                           radius=int(300 * 4 * 0.2237), fill=255)
    tile.putalpha(mask.resize((300, 300), Image.LANCZOS))

    shadow = Image.new("RGBA", (CARD_W, CARD_H), (0, 0, 0, 0))
    shadow.paste((0, 0, 0, 150), (118, 178, 118 + 300, 178 + 300), tile.split()[3])
    shadow = shadow.filter(ImageFilter.GaussianBlur(22))
    card = Image.alpha_composite(card.convert("RGBA"), shadow)
    card.paste(tile, (110, 165), tile)

    title_font = load_font(112, bold=True)
    tag_font = load_font(40, bold=False)
    word = gradient_text(TITLE, title_font, BRAND)
    card.alpha_composite(word, (470, 214))
    d = ImageDraw.Draw(card)
    # Measured and wrapped rather than trusted: the second line ran off the
    # right edge of the card at this size, which is the one thing a preview
    # image cannot get away with.
    lines = [TAGLINE] + CARD_LINES
    y = 372
    for i, line in enumerate(lines):
        col = SOFT if i == 0 else (120, 114, 124)
        while d.textbbox((0, 0), line, font=tag_font)[2] > CARD_W - 474 - 60 and len(line) > 4:
            line = line[:-2] + "\u2026"
        d.text((474, y), line, font=tag_font, fill=col)
        y += 54
    return card.convert("RGB")



def write_share_page():
    meta = META.format(begin=BEGIN, end=END, desc=DESC, site=SITE, w=CARD_W, h=CARD_H, card=CARD_REV)
    meta = meta.replace('<meta property="og:url" content="%s">' % SITE,
                        '<meta property="og:url" content="%sshare/">' % SITE)
    io.open(SHARE_PAGE, "w", encoding="utf-8").write(SHARE_HTML.format(meta=meta, site=SITE, rev=ICON_REV))


def write_meta():
    src = io.open(INDEX, encoding="utf-8").read()
    block = META.format(begin=BEGIN, end=END, desc=DESC, site=SITE,
                        w=CARD_W, h=CARD_H, card=CARD_REV)
    if BEGIN in src and END in src:
        head = src.index(BEGIN)
        tail = src.index(END) + len(END)
        src = src[:head] + block + src[tail:]
    else:
        # Right after the title, so a crawler that stops reading early has it.
        anchor = "<meta name=\"apple-mobile-web-app-title\" content=\"Nova\">"
        assert src.count(anchor) == 1, "anchor for the share block moved"
        src = src.replace(anchor, anchor + "\n" + block, 1)
    io.open(INDEX, "w", encoding="utf-8").write(src)


def check():
    problems = []
    for name, size in [("og-card.png", (CARD_W, CARD_H)), ("icon-512.png", (ICON_PX, ICON_PX))]:
        path = os.path.join(SHARE, name)
        if not os.path.exists(path):
            problems.append("share/%s is missing" % name)
            continue
        with Image.open(path) as im:
            if im.size != size:
                problems.append("share/%s is %s, expected %s" % (name, im.size, size))
    src = io.open(INDEX, encoding="utf-8").read()
    for needed in ['property="og:image" content="%sshare/og-card.png?v=%s"' % (SITE, CARD_REV),
                   'name="twitter:image" content="%sshare/og-card.png?v=%s"' % (SITE, CARD_REV),
                   'property="og:title"', 'name="description"']:
        if needed not in src:
            problems.append("index.html is missing %s" % needed)
    if not os.path.exists(SHARE_PAGE):
        problems.append("share/index.html (the page that is shared) is missing")
    else:
        page = io.open(SHARE_PAGE, encoding="utf-8").read()
        if len(page.encode("utf-8")) > 8000:
            problems.append("share/index.html is over 8KB - it exists to be small")
        for needed in ['property="og:image" content="%sshare/og-card.png?v=%s"' % (SITE, CARD_REV), 'content="%s"' % DESC,
                       'share/apple-touch-icon.png?v=%s' % ICON_REV, 'location.replace("../"']:
            if needed not in page:
                problems.append("share/index.html is missing %s" % needed)
    if ('const SHARE_URL = "%sshare/?v=%s"' % (SITE, CARD_REV)) not in src:
        problems.append("the Share button does not send the share page (SHARE_URL)")
    if ('share/apple-touch-icon.png?v=%s' % ICON_REV) not in src:
        problems.append("index.html's apple-touch-icon is not at ?v=%s" % ICON_REV)
    if ('content="%s"' % DESC) not in src:
        problems.append("index.html's description is not the current one")
    block = src.split(END)[0].split(BEGIN)[-1]
    if "26E" in block:
        problems.append("the share block names Class 26E; a link preview must not")
    for p in problems:
        print("  FAIL " + p)
    if not problems:
        print("  share/og-card.png and share/icon-512.png present, meta points at them")
    return 1 if problems else 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="verify the files exist and the meta names them")
    args = ap.parse_args()
    if args.check:
        return check()

    icon_mod = load_icon_module()
    icon = icon_mod.render("pixel", size=ICON_PX).convert("RGB")
    os.makedirs(SHARE, exist_ok=True)
    icon.save(os.path.join(SHARE, "icon-512.png"), optimize=True)
    build_card(icon).save(os.path.join(SHARE, "og-card.png"), optimize=True)
    write_meta()
    write_share_page()
    print("wrote share/og-card.png (%dx%d), share/icon-512.png (%d), and the meta block"
          % (CARD_W, CARD_H, ICON_PX))
    return 0


if __name__ == "__main__":
    sys.exit(main())

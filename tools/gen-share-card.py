"""The images a link preview needs, as REAL FILES, plus the meta that names them.

Sharing the app used to produce a card in iMessage with the icon on it and
the app's own colour behind it, and it stopped. The page had no Open Graph
metadata at all - no og:image, no og:title, no og:description - so every
preview was working from whatever it could scrape, and the one thing it
could have scraped is `apple-touch-icon`, which is a base64 `data:` URI.

That is the same lesson `launch/` already cost a session: iOS wants a
FETCHABLE PATH. A crawler asks for the page and then asks for the image;
it does not decode a data URI out of the markup and treat it as a remote
resource. So this writes two real files and points the metadata at them.

  share/og-card.png   1200x630, the wide card most previews show
  share/icon-512.png  square, for the ones that want an icon

Paths are ABSOLUTE since build 342 (SITE). Madison's shared link showed no
icon: crawlers (iMessage's among them) are not reliable about resolving a
relative og:image, and the app is served from one place now. If the app moves,
change SITE and run this again. The preview does not name a class.

  python3 tools/gen-share-card.py           # write the files and the meta
  python3 tools/gen-share-card.py --check   # verify both exist and match
"""

def block(url):
    return META.format(begin=BEGIN, end=END, desc=DESC, site=SITE, w=CARD_W, h=CARD_H, card=CARD_REV, url=url)


def write_share_page():
    io.open(SHARE_PAGE, "w", encoding="utf-8").write(SHARE_HTML.format(meta=block(SITE + "share/"), site=SITE, rev=ICON_REV))


def write_meta():
    src = io.open(INDEX, encoding="utf-8").read()
    end_head = src.index("</head>")
    head, rest = src[:end_head], src[end_head:]
    # take the old block out wherever it is (it used to sit 45KB in), and the lone <title> that sat past the manifest
    if BEGIN in head and END in head:
        a = head.index(BEGIN)
        z = head.index(END) + len(END)
        head = head[:a] + head[z:].lstrip("\n")
    head = head.replace("<title>Nova</title>\n", "", 1)
    assert head.count("<title") == 0, "another <title> is in the head"
    assert head.count(HEAD_ANCHOR) == 1, "anchor for the share block moved"
    head = head.replace(HEAD_ANCHOR, HEAD_ANCHOR + "\n" + block(SITE), 1)
    src = head + rest
    # the Share button's address is versioned with the card (iMessage keeps a link's preview by its address)
    src, n = re.subn(r'const SHARE_URL = "[^"]*";', 'const SHARE_URL = "%sshare/?v=%s";' % (SITE, CARD_REV), src)
    assert n == 1, "SHARE_URL moved"
    io.open(INDEX, "w", encoding="utf-8").write(src)


def check():
    problems = []
    for name, size in [("og-card.png", (CARD_W, CARD_H)), ("icon-512.png", (ICON_PX, ICON_PX))]:
        path = os.path.join(SHARE, name)
        if not os.path.exists(path):
            problems.append("share/%s is missing" % name)
            continue
        with Image.open(path) as im:
            if im.size != size:
                problems.append("share/%s is %s, expected %s" % (name, im.size, size))
    src = io.open(INDEX, encoding="utf-8").read()
    for needed in ['property="og:image" content="%sshare/og-card.png?v=%s"' % (SITE, CARD_REV),
                   'name="twitter:image" content="%sshare/og-card.png?v=%s"' % (SITE, CARD_REV),
                   'property="og:title"', 'name="description"']:
        if needed not in src:
            problems.append("index.html is missing %s" % needed)
    if not os.path.exists(SHARE_PAGE):
        problems.append("share/index.html (the page that is shared) is missing")
    else:
        page = io.open(SHARE_PAGE, encoding="utf-8").read()
        if len(page.encode("utf-8")) > 8000:
            problems.append("share/index.html is over 8KB - it exists to be small")
        for needed in ['property="og:image" content="%sshare/og-card.png?v=%s"' % (SITE, CARD_REV), 'content="%s"' % DESC,
                       'share/apple-touch-icon.png?v=%s' % ICON_REV, 'location.replace("../"']:
            if needed not in page:
                problems.append("share/index.html is missing %s" % needed)
    if ('const SHARE_URL = "%sshare/?v=%s"' % (SITE, CARD_REV)) not in src:
        problems.append("the Share button does not send the share page (SHARE_URL)")
    if ('share/apple-touch-icon.png?v=%s' % ICON_REV) not in src:
        problems.append("index.html's apple-touch-icon is not at ?v=%s" % ICON_REV)
    if ('content="%s"' % DESC) not in src:
        problems.append("index.html's description is not the current one")
    # (384.38) the tags a preview reads must END inside the first MAX_META_END bytes of each document, and <title> be there once
    for label, doc in (("index.html", src), ("share/index.html", io.open(SHARE_PAGE, encoding="utf-8").read() if os.path.exists(SHARE_PAGE) else "")):
        raw = doc.encode("utf-8")
        if raw.count(b"<title") != 1 or raw.index(b"<title") > MAX_META_END:
            problems.append("%s: <title> is not one tag inside the first %d bytes" % (label, MAX_META_END))
        for key in ('property="og:title"', 'property="og:description"', 'property="og:image"', 'name="twitter:card"', 'name="twitter:title"',
                    'name="twitter:description"', 'name="twitter:image"', 'name="description"'):
            at = raw.find(key.encode())
            end = raw.find(b">", at) + 1 if at >= 0 else -1
            if at < 0 or end > MAX_META_END:
                problems.append("%s: %s ends at byte %d, past the first %d (a crawler that stops early never sees it)" % (label, key, end, MAX_META_END))
        if raw.find(END.encode()) + len(END) > MAX_META_END:
            problems.append("%s: the share block runs past byte %d" % (label, MAX_META_END))
    block = src.split(END)[0].split(BEGIN)[-1]
    if "26E" in block:
        problems.append("the share block names Class 26E; a link preview must not")
    for p in problems:
        print("  FAIL " + p)
    if not problems:
        print("  share/og-card.png and share/icon-512.png present, meta points at them")
    return 1 if problems else 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="verify the files exist and the meta names them")
    args = ap.parse_args()
    if args.check:
        return check()

    icon_mod = load_icon_module()
    icon = icon_mod.render("pixel", size=ICON_PX).convert("RGB")
    os.makedirs(SHARE, exist_ok=True)
    icon.save(os.path.join(SHARE, "icon-512.png"), optimize=True)
    build_card(icon).save(os.path.join(SHARE, "og-card.png"), optimize=True)
    write_meta()
    write_share_page()
    print("wrote share/og-card.png (%dx%d), share/icon-512.png (%d), and the meta block"
          % (CARD_W, CARD_H, ICON_PX))
    return 0


if __name__ == "__main__":
    sys.exit(main())
